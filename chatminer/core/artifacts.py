"""
Artifact Extractor — find code, documents, files, and references IN conversations
=================================================================================

Scans parsed messages for:
    - Code blocks (```fenced```) → code snippets
    - File references (.docx, .json, etc. mentioned or attached)
    - URLs and external links
    - Document artifacts created in-chat (.docx generated by AI)
    - Evidence references (texts, emails, photos mentioned)

This is the bridge between "raw conversation text" and "actionable artifacts
that can be used for legal strategy or platform development."

Usage:
    from chatminer.core.artifacts import extract_artifacts
    
    artifacts = extract_artifacts(messages)
    for art in artifacts:
        print(f"{art.artifact_type.value}: {art.title}")
"""

from __future__ import annotations

import logging
import re
import uuid
from datetime import datetime
from typing import Optional

from chatminer.core.types import (
    Artifact,
    ArtifactType,
    ContentType,
    ParsedMessage,
)

logger = logging.getLogger(__name__)

# --- Detection patterns ---

# Code fence with language
_CODE_FENCE_RE = re.compile(r"```(\w+)?\n(.*?)```", re.DOTALL)

# File references: [filename.ext], filename.ext, or "file: ..."
_FILE_REF_RE = re.compile(
    r"(?:\b|\[)([\w\-./]+\.(?:docx?|pdf|json|csv|xlsx?|txt|md|py|js|ts|html|png|jpe?g|gif))(?:\b|\])",
    re.IGNORECASE,
)

# URL detection
_URL_RE = re.compile(
    r"https?://[^\s<>\"{}|\\^`[\]]+(?:\([^\s)]*\))?"
)

# Evidence references
_EVIDENCE_PATTERNS = [
    re.compile(r"\b(texts?|messages?|emails?|screenshots?|photos?|pictures?|videos?|recordings?|calls?)\b", re.I),
    re.compile(r"\b(evidence|proof|documentation|records?)\b", re.I),
    re.compile(r"\b(affidavit|deposition|testimony|statement)\b", re.I),
]

# Document creation indicators
_DOC_CREATION_PATTERNS = [
    re.compile(r"(?:created|generated|wrote)\s+(?:a\s+)?(?:document|file)\s+(?:called|named)?\s*[\"']?([\w\-./]+\.\w+)[\"']?", re.I),
    re.compile(r"(?:here's|here is)\s+(?:the\s+)?(?:document|file)\s*[\"']?([\w\-./]+\.\w+)[\"']?", re.I),
    re.compile(r"```\s*(?:markdown|md)\s*\n#\s*(.+\.(?:docx?|pdf|md))", re.I),
]

# Strategy/theory indicators
_STRATEGY_PATTERNS = [
    re.compile(r"\b(strategy|approach|plan|tactic)\s+(?:is|would be|should be)\b", re.I),
    re.compile(r"\b(theory|argument|claim|defense)\s*:?\s*(?:is|of)\b", re.I),
    re.compile(r"\b(legal\s+(?:strategy|approach|theory|argument))\b", re.I),
]


def extract_artifacts(messages: list[ParsedMessage]) -> list[Artifact]:
    """
    Extract all artifacts from a list of parsed messages.

    This is the main entry point. It runs all extractors and returns
    a combined list of artifacts found across all messages.
    """
    artifacts: list[Artifact] = []

    # Run each extractor
    artifacts.extend(_extract_code_blocks(messages))
    artifacts.extend(_extract_file_references(messages))
    artifacts.extend(_extract_urls(messages))
    artifacts.extend(_extract_document_artifacts(messages))
    artifacts.extend(_extract_evidence_references(messages))
    artifacts.extend(_extract_strategy_mentions(messages))

    # Deduplicate by content hash
    seen = set()
    deduped = []
    for art in artifacts:
        h = hash((art.artifact_type.value, art.title or "", (art.content or "")[:100]))
        if h not in seen:
            seen.add(h)
            deduped.append(art)

    return deduped


def _extract_code_blocks(messages: list[ParsedMessage]) -> list[Artifact]:
    """Extract fenced code blocks as code snippet artifacts."""
    artifacts: list[Artifact] = []

    for msg in messages:
        if msg.content_type != ContentType.CODE:
            # Also check messages marked as TEXT that contain code fences
            if "```" not in msg.content:
                continue

        matches = _CODE_FENCE_RE.findall(msg.content)
        for i, (lang, code) in enumerate(matches):
            if len(code.strip()) < 10:
                continue  # Skip tiny snippets

            title = f"code_snippet_{i+1}"
            if lang:
                title = f"{lang}_snippet_{i+1}"

            art = Artifact(
                artifact_id=str(uuid.uuid4()),
                artifact_type=ArtifactType.CODE_SNIPPET,
                source_message_id=msg.message_id,
                source_conversation_id=msg.source_file,
                title=title,
                content=code.strip(),
                language=lang or "text",
                metadata={
                    "sender": msg.sender,
                    "timestamp": msg.timestamp.isoformat() if msg.timestamp else None,
                },
            )
            artifacts.append(art)

    return artifacts


def _extract_file_references(messages: list[ParsedMessage]) -> list[Artifact]:
    """Extract references to files mentioned in conversation."""
    artifacts: list[Artifact] = []

    for msg in messages:
        matches = _FILE_REF_RE.findall(msg.content)
        for fname in matches:
            # Skip common false positives
            if fname.lower() in ("README.md", ".gitignore", "package.json"):
                continue

            art = Artifact(
                artifact_id=str(uuid.uuid4()),
                artifact_type=ArtifactType.DATA_FILE,
                source_message_id=msg.message_id,
                source_conversation_id=msg.source_file,
                title=fname,
                metadata={
                    "sender": msg.sender,
                    "mentioned_in": msg.content[:200],
                },
            )
            artifacts.append(art)

    return artifacts


def _extract_urls(messages: list[ParsedMessage]) -> list[Artifact]:
    """Extract URLs mentioned in conversation."""
    artifacts: list[Artifact] = []
    seen_urls = set()

    for msg in messages:
        matches = _URL_RE.findall(msg.content)
        for url in matches:
            url = url.strip()
            if url in seen_urls:
                continue
            seen_urls.add(url)

            art = Artifact(
                artifact_id=str(uuid.uuid4()),
                artifact_type=ArtifactType.URL,
                source_message_id=msg.message_id,
                source_conversation_id=msg.source_file,
                title=url[:80],
                metadata={"url": url, "sender": msg.sender},
            )
            artifacts.append(art)

    return artifacts


def _extract_document_artifacts(messages: list[ParsedMessage]) -> list[Artifact]:
    """Extract documents that were created/generated during the conversation."""
    artifacts: list[Artifact] = []

    for msg in messages:
        if msg.sender_role.value != "assistant":
            continue  # Documents are usually created by the assistant

        for pattern in _DOC_CREATION_PATTERNS:
            m = pattern.search(msg.content)
            if m:
                fname = m.group(1)
                art = Artifact(
                    artifact_id=str(uuid.uuid4()),
                    artifact_type=ArtifactType.DOCUMENT,
                    source_message_id=msg.message_id,
                    source_conversation_id=msg.source_file,
                    title=fname,
                    metadata={
                        "sender": msg.sender,
                        "created_in_chat": True,
                    },
                )
                artifacts.append(art)

    return artifacts


def _extract_evidence_references(messages: list[ParsedMessage]) -> list[Artifact]:
    """Extract references to evidence items mentioned in conversation."""
    artifacts: list[Artifact] = []

    for msg in messages:
        for pattern in _EVIDENCE_PATTERNS:
            if pattern.search(msg.content):
                # Extract the surrounding context (sentence containing the match)
                sentences = re.split(r"[.!?]+", msg.content)
                for sent in sentences:
                    if pattern.search(sent):
                        art = Artifact(
                            artifact_id=str(uuid.uuid4()),
                            artifact_type=ArtifactType.EVIDENCE_REFERENCE,
                            source_message_id=msg.message_id,
                            source_conversation_id=msg.source_file,
                            title=sent.strip()[:100],
                            metadata={
                                "sender": msg.sender,
                                "evidence_type": pattern.pattern[:30],
                            },
                        )
                        artifacts.append(art)
                        break  # One per pattern per message

    return artifacts


def _extract_strategy_mentions(messages: list[ParsedMessage]) -> list[Artifact]:
    """Extract legal strategy or theory discussions."""
    artifacts: list[Artifact] = []

    for msg in messages:
        for pattern in _STRATEGY_PATTERNS:
            if pattern.search(msg.content):
                # Get the sentence containing the strategy
                sentences = re.split(r"[.!?]+", msg.content)
                for sent in sentences:
                    if pattern.search(sent):
                        art = Artifact(
                            artifact_id=str(uuid.uuid4()),
                            artifact_type=ArtifactType.STRATEGY_DOC,
                            source_message_id=msg.message_id,
                            source_conversation_id=msg.source_file,
                            title=sent.strip()[:120],
                            content=sent.strip(),
                            metadata={"sender": msg.sender},
                        )
                        artifacts.append(art)
                        break

    return artifacts
