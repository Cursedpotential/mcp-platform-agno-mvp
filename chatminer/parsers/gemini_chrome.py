"""
Gemini Chrome Extension Parser
==============================

Parses conversation exports from the Google Gemini Chrome extension.
These are markdown files with a specific header showing conversation
details and emoji-delimited message blocks.

Source Format (from your actual files):
    Google Gemini
    Conversation Details
    Exported on: 12/9/2025, 4:34:05 PM | Total Messages: 5
    🤖 Assistant (4:34:00 PM)
    [Message content...]
    👤 You (4:34:05 PM)
    [Follow-up question...]

The extension creates files named: Google_Gemini_YYYY-MM-DD_HHMM.md

Usage:
    parser = GeminiChromeParser()
    result = parser.parse_file("Google_Gemini_2025-12-09_1634.md")
"""

from __future__ import annotations

import logging
import re
import uuid
from datetime import datetime
from typing import Optional

from chatminer.core.base import BaseParser, ParserConfig
from chatminer.core.types import ContentType, MessageRole, ParsedConversation, ParsedMessage

logger = logging.getLogger(__name__)


class GeminiChromeParser(BaseParser):
    """
    Parser for Google Gemini Chrome extension exports.

    These files are generated by the official Gemini Chrome extension
    export feature. They use emoji markers (🤖, 👤) to separate
    assistant and user messages, with timestamps.
    """

    SUPPORTED_FORMATS = [".md", ".txt"]
    SOURCE_NAME = "gemini_chrome"

    # --- Detection patterns ---
    # Header line: "Google Gemini" or "Gemini"
    _HEADER_RE = re.compile(r"^\s*#?\s*Google\s+Gemini\b", re.IGNORECASE)
    # "Exported on: MM/DD/YYYY, HH:MM:SS AM/PM"
    _EXPORTED_RE = re.compile(
        r"Exported\s+on:\s+(\d{1,2}/\d{1,2}/\d{4},?\s+\d{1,2}:\d{2}:\d{2}\s*(?:AM|PM)?)",
        re.IGNORECASE,
    )
    # "Total Messages: N"
    _TOTAL_MSGS_RE = re.compile(r"Total\s+Messages:\s*(\d+)", re.IGNORECASE)
    # Message separators: 🤖 Assistant (timestamp) or 👤 You (timestamp)
    _ASSISTANT_MSG_RE = re.compile(
        r"^\s*🤖\s+Assistant\s*(?:\(([^)]+)\))?\s*$"
    )
    _USER_MSG_RE = re.compile(
        r"^\s*(?:👤|🧑)\s+(?:You|User)\s*(?:\(([^)]+)\))?\s*$"
    )
    # Code fence
    _CODE_FENCE_RE = re.compile(r"```(\w+)?")

    def can_parse(self, content: str, path: Optional[str] = None) -> float:
        """Detect Gemini Chrome extension format."""
        score = 0.0

        # Check for "Google Gemini" header
        if self._HEADER_RE.search(content):
            score += 0.4

        # Check for "Exported on:" line
        if self._EXPORTED_RE.search(content):
            score += 0.3

        # Check for "Total Messages:" line
        if self._TOTAL_MSGS_RE.search(content):
            score += 0.1

        # Check for emoji message markers
        if "🤖" in content and ("👤" in content or "🧑" in content):
            score += 0.2

        # Filename hint
        if path and "gemini" in path.lower():
            score += 0.1

        return min(score, 1.0)

    def parse_content(self, content: str, source_file: str = "") -> list[ParsedConversation]:
        """Parse Gemini Chrome extension markdown into conversations."""
        lines = content.split("\n")

        conv = ParsedConversation(
            conversation_id=str(uuid.uuid4()),
            source_file=source_file,
            source_format=self.SOURCE_NAME,
        )

        # --- Step 1: Extract header metadata ---
        header_end = 0
        for i, line in enumerate(lines):
            # "Google Gemini" or "Gemini" title
            if self._HEADER_RE.match(line):
                conv.title = "Gemini Conversation"
                header_end = max(header_end, i + 1)
                continue

            # "Exported on: ..."
            m = self._EXPORTED_RE.search(line)
            if m:
                ts_str = m.group(1)
                try:
                    # Try multiple formats
                    for fmt in ["%m/%d/%Y, %I:%M:%S %p", "%m/%d/%Y %I:%M:%S %p"]:
                        try:
                            dt = datetime.strptime(ts_str.strip(), fmt)
                            conv.metadata["exported_at"] = dt.isoformat()
                            break
                        except ValueError:
                            continue
                except Exception:
                    pass
                header_end = max(header_end, i + 1)
                continue

            # "Total Messages: N"
            m = self._TOTAL_MSGS_RE.search(line)
            if m:
                conv.metadata["total_messages_expected"] = int(m.group(1))
                header_end = max(header_end, i + 1)
                continue

            # "Conversation Details" is just a label
            if "conversation details" in line.lower():
                header_end = max(header_end, i + 1)
                continue

        # --- Step 2: Extract messages ---
        messages = self._extract_messages(lines, header_end, source_file)
        conv.messages = messages

        return [conv]

    def _extract_messages(
        self, lines: list[str], start_index: int, source_file: str
    ) -> list[ParsedMessage]:
        """Extract messages using emoji role markers."""
        messages: list[ParsedMessage] = []
        current_role: MessageRole = MessageRole.USER
        current_content: list[str] = []
        current_timestamp: Optional[str] = None
        msg_index = 0

        i = start_index
        while i < len(lines):
            line = lines[i]

            # Detect assistant message start
            m = self._ASSISTANT_MSG_RE.match(line)
            if m:
                # Save previous message
                if current_content:
                    content = "\n".join(current_content).strip()
                    if content:
                        messages.append(
                            self._create_message(
                                content=content,
                                role=current_role,
                                source_file=source_file,
                                index=msg_index,
                                timestamp_str=current_timestamp,
                            )
                        )
                        msg_index += 1
                    current_content = []
                current_role = MessageRole.ASSISTANT
                current_timestamp = m.group(1)
                i += 1
                continue

            # Detect user message start
            m = self._USER_MSG_RE.match(line)
            if m:
                if current_content:
                    content = "\n".join(current_content).strip()
                    if content:
                        messages.append(
                            self._create_message(
                                content=content,
                                role=current_role,
                                source_file=source_file,
                                index=msg_index,
                                timestamp_str=current_timestamp,
                            )
                        )
                        msg_index += 1
                    current_content = []
                current_role = MessageRole.USER
                current_timestamp = m.group(1)
                i += 1
                continue

            # Regular content
            current_content.append(line)
            i += 1

        # Save final message
        if current_content:
            content = "\n".join(current_content).strip()
            if content:
                messages.append(
                    self._create_message(
                        content=content,
                        role=current_role,
                        source_file=source_file,
                        index=msg_index,
                        timestamp_str=current_timestamp,
                    )
                )

        return messages

    def _create_message(
        self,
        content: str,
        role: MessageRole,
        source_file: str,
        index: int,
        timestamp_str: Optional[str] = None,
    ) -> ParsedMessage:
        """Create a ParsedMessage with content type detection."""
        # Parse timestamp if present
        ts: Optional[datetime] = None
        if timestamp_str:
            for fmt in ["%I:%M %p", "%H:%M", "%I:%M:%S %p"]:
                try:
                    ts = datetime.strptime(timestamp_str.strip(), fmt)
                    break
                except ValueError:
                    continue

        # Detect content type
        content_type = ContentType.TEXT
        language: Optional[str] = None

        if "```" in content:
            content_type = ContentType.CODE
            m = self._CODE_FENCE_RE.search(content)
            if m and m.group(1):
                language = m.group(1)

        return ParsedMessage(
            message_id=str(uuid.uuid4()),
            source_file=source_file,
            source_format=self.SOURCE_NAME,
            source_index=index,
            timestamp=ts,
            sender="You" if role == MessageRole.USER else "Gemini",
            sender_role=role,
            content=content,
            content_type=content_type,
            language=language,
            confidence="HIGH",
            metadata={},
        )
